// The proxy a Process narrowed to named hosts is forced through
// (spec/v1/16-dependencies.md#host-narrowed-egress): its name, its port, the
// configuration that admits the hosts the author wrote and nothing else, and
// the variables that point the Process's clients at it. No project file writes
// any of them.
import type { ProcessDocument } from "./project-intent.ts";

type Egress = NonNullable<ProcessDocument["egress"]>;
export type HostEgress = Extract<Egress, { readonly hosts: unknown }>;
export type EgressHost = HostEgress["hosts"][number];

/** The surface the proxy answers on, and the port it listens on. */
export const PROXY_SURFACE = "proxy";
export const PROXY_PORT = 3128;

/** Where the proxy reads its configuration, and writes what it must. */
export const PROXY_CONFIG = "/etc/squid/squid.conf";
export const PROXY_WRITABLE = ["/tmp"] as const;

/** The Process the proxy of `process` is. */
export const egressProxyName = (process: string): string => `${process}-egress`;

/** Whether an authored `egress` is the host-narrowed form. */
export const isHostEgress = (
  egress: Egress | undefined,
): egress is HostEgress => egress !== undefined && "hosts" in egress;

/** The hosts a Process may reach, each pair once, in name then port order. */
export const hostsOf = (egress: HostEgress): EgressHost[] => {
  const held = new Map(
    egress.hosts.map(({ host, port }) => [
      `${host}:${String(port)}`,
      { host, port },
    ]),
  );
  return [...held.values()].toSorted(
    (left, right) =>
      left.host.localeCompare(right.host) || left.port - right.port,
  );
};

/** Each port the hosts are reached on, once, ascending. */
export const portsOfHosts = (hosts: readonly EgressHost[]): number[] =>
  [...new Set(hosts.map(({ port }) => port))].toSorted((a, b) => a - b);

/**
 * The proxy's configuration: one allow rule per host and port, a refusal of
 * every request that names an address instead of a name (a destination
 * matched by its reverse DNS would be the address owner's to name), and a
 * final denial of everything else. Nothing is cached or logged beyond the
 * container's own streams.
 */
export const proxyConfigOf = (
  process: string,
  hosts: readonly EgressHost[],
): string =>
  [
    `# Generated by deploy-kit: the hosts ${process} may reach, and nothing else.`,
    `http_port ${String(PROXY_PORT)}`,
    "pid_filename none",
    "cache deny all",
    "cache_log /dev/stderr",
    "access_log stdio:/dev/stdout",
    "coredump_dir /tmp",
    "dns_v4_first on",
    "via off",
    "pinger_enable off",
    "forwarded_for delete",
    String.raw`acl numeric dstdom_regex -i ^[0-9.]+$ ^\[?[0-9a-f]*:[0-9a-f:.]*\]?$`,
    "http_access deny numeric",
    ...hosts.flatMap(({ host, port }, index) => [
      `acl host${String(index)} dstdomain ${host}`,
      `acl port${String(index)} port ${String(port)}`,
      `http_access allow host${String(index)} port${String(index)}`,
    ]),
    "http_access deny all",
    "",
  ].join("\n");

/** What a client keeps off the proxy: the cluster's own names and the loopback. */
const LOCAL_NAMES = [
  "localhost",
  "127.0.0.1",
  ".svc",
  ".svc.cluster.local",
  ".cluster.local",
];

/**
 * The variables Go, curl, Python and Node clients read to reach beyond the
 * cluster through the proxy, spelled in both cases, and the names kept off it:
 * the cluster's own and every host its edges reach.
 */
export const proxyEnvironmentOf = (
  proxy: string,
  edgeHosts: readonly string[],
): { name: string; value: string }[] => {
  const url = `http://${proxy}:${String(PROXY_PORT)}`;
  const kept = [...new Set([...LOCAL_NAMES, proxy, ...edgeHosts])].join(",");
  return [
    ["HTTPS_PROXY", url],
    ["HTTP_PROXY", url],
    ["NO_PROXY", kept],
    ["http_proxy", url],
    ["https_proxy", url],
    ["no_proxy", kept],
  ].map(([name, value]) => ({
    name: name as string,
    value: value as string,
  }));
};
