// An Application's generated identity file (spec/v1/17-sign-in.md#generated-app-roles):
// its App Roles, user first and then the declared roles in order, its Client id
// and the Principal contract version it expects, as source text in the
// application's own language. Every value is a plain string, so the file
// depends on no adapter library.
import type { IDENTITY_LANGUAGES } from "../model/vocabularies.ts";

export type IdentityLanguage = (typeof IDENTITY_LANGUAGES)[number];

/** What a generated identity file states. */
export interface IdentityDeclaration {
  /** The Client the Application's tokens are for: the Application Id. */
  readonly client: string;
  /** Every App Role, `user` first, then the declared roles in order. */
  readonly roles: readonly string[];
  /** The Principal contract version the Application expects, major.minor. */
  readonly contract: string;
}

/** Why a declaration cannot be written in a language. */
export interface Unwritable {
  readonly message: string;
}

const HEADER = "Code generated by deploy-kit generate identity; DO NOT EDIT.";

const about = (client: string): string =>
  `The App Roles, the Client id and the Principal contract version of ${client},\n` +
  "from its client block (spec/v1/17-sign-in.md#generated-app-roles).";

/** A role's name in PascalCase: `release-manager` is `ReleaseManager`. */
const pascal = (role: string): string =>
  role
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");

/** A role's name as a constant: `release-manager` is `RELEASE_MANAGER`. */
const screaming = (role: string): string =>
  role.toUpperCase().replaceAll("-", "_");

/** The first two roles one naming spells alike, if any. */
function collision(
  roles: readonly string[],
  name: (role: string) => string,
): Unwritable | undefined {
  const seen = new Map<string, string>();
  for (const role of roles) {
    const spelt = name(role);
    const other = seen.get(spelt);
    if (other !== undefined)
      return {
        message: `the roles ${other} and ${role} are both ${spelt}; rename one in the client block`,
      };
    seen.set(spelt, role);
  }
  return undefined;
}

/**
 * A list on one line where it fits within `width`, and one item a line, each
 * with a trailing comma, where it does not: as prettier and rustfmt lay out a
 * literal, so a formatter check in the application leaves the file alone.
 */
function list(
  opening: string,
  items: readonly string[],
  closing: string,
  layout: Layout,
): string {
  const line = `${opening}${items.join(", ")}${closing}`;
  // The literal itself: its brackets and what is between them.
  const literal = `[${items.join(", ")}]`;
  if (line.length <= layout.width && literal.length <= layout.literal)
    return line;
  const at = INDENT_OF(opening);
  return [
    opening,
    ...items.map((item) => `${at}${layout.indent}${item},`),
    `${at}${closing}`,
  ].join("\n");
}

/**
 * How a formatter lays out a list literal: the longest line, the longest
 * literal on one line, and the indent of an item on its own.
 */
interface Layout {
  readonly width: number;
  readonly literal: number;
  readonly indent: string;
}

/** prettier wraps at the line's width alone. */
const PRETTIER: Layout = { width: 80, literal: 80, indent: "  " };
/** rustfmt also wraps an array literal over 60% of its width (`array_width`). */
const RUSTFMT: Layout = { width: 100, literal: 60, indent: "    " };

/** The leading spaces of a line. */
const INDENT_OF = (line: string): string =>
  line.slice(0, line.length - line.trimStart().length);

const comment = (prefix: string, text: string): string =>
  text
    .split("\n")
    .map((line) => `${prefix} ${line}`)
    .join("\n");

function go({ client, roles, contract }: IdentityDeclaration): string {
  const names = roles.map((role) => `Role${pascal(role)}`);
  const width = Math.max(...names.map((name) => name.length));
  return `${comment("//", `${HEADER}\n${about(client)}`)}

package identity

// ClientID is the Client the Application's tokens are for.
const ClientID = "${client}"

// ContractVersion is the Principal contract version the Application expects.
const ContractVersion = "${contract}"

// Role is an App Role the Application declares.
type Role string

// The Application's App Roles.
const (
${names.map((name, i) => `\t${name.padEnd(width)} Role = "${roles[i] as string}"`).join("\n")}
)

// Roles is every App Role, user first, then the declared roles in order.
var Roles = []Role{${names.join(", ")}}
`;
}

function kotlin(
  { client, roles, contract }: IdentityDeclaration,
  pkg: string,
): string {
  return `${comment("//", `${HEADER}\n${about(client)}`)}

package ${pkg}

/** The Client the Application's tokens are for. */
const val CLIENT_ID: String = "${client}"

/** The Principal contract version the Application expects. */
const val CONTRACT_VERSION: String = "${contract}"

/** An App Role the Application declares, user first, then the declared roles in order. */
enum class AppRole(val value: String) {
${roles.map((role) => `    ${screaming(role)}("${role}"),`).join("\n")}
}
`;
}

function typescript({ client, roles, contract }: IdentityDeclaration): string {
  return `${comment("//", `${HEADER}\n${about(client)}`)}

/** The Client the Application's tokens are for. */
export const CLIENT_ID = "${client}";

/** The Principal contract version the Application expects. */
export const CONTRACT_VERSION = "${contract}";

/** Every App Role, user first, then the declared roles in order. */
${list(
  "export const APP_ROLES = [",
  roles.map((role) => `"${role}"`),
  "] as const;",
  PRETTIER,
)}

/** An App Role the Application declares. */
export type AppRole = (typeof APP_ROLES)[number];
`;
}

function python({ client, roles, contract }: IdentityDeclaration): string {
  return `${comment("#", `${HEADER}\n${about(client)}`)}

from enum import Enum
from typing import Final

CLIENT_ID: Final = "${client}"
"""The Client the Application's tokens are for."""

CONTRACT_VERSION: Final = "${contract}"
"""The Principal contract version the Application expects."""


class AppRole(str, Enum):
    """An App Role: user first, then the declared roles in order."""

${roles.map((role) => `    ${screaming(role)} = "${role}"`).join("\n")}
`;
}

function rust({ client, roles, contract }: IdentityDeclaration): string {
  const variants = roles.map(pascal);
  return `${comment("//", `${HEADER}\n${about(client)}`)}

/// The Client the Application's tokens are for.
pub const CLIENT_ID: &str = "${client}";

/// The Principal contract version the Application expects.
pub const CONTRACT_VERSION: &str = "${contract}";

/// An App Role the Application declares.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum AppRole {
${variants.map((variant) => `    ${variant},`).join("\n")}
}

impl AppRole {
    /// Every App Role, user first, then the declared roles in order.
${list(
  `    pub const ALL: [AppRole; ${String(roles.length)}] = [`,
  variants.map((variant) => `AppRole::${variant}`),
  "];",
  RUSTFMT,
)}

    /// The role as identity names it.
    pub const fn as_str(self) -> &'static str {
        match self {
${variants.map((variant, i) => `            AppRole::${variant} => "${roles[i] as string}",`).join("\n")}
        }
    }
}
`;
}

/** A Kotlin package name: dot-separated identifiers. */
const KOTLIN_PACKAGE = /^[A-Za-z_][A-Za-z0-9_]*(\.[A-Za-z_][A-Za-z0-9_]*)*$/;

/** Rust's one keyword a PascalCase role can spell. */
const RUST_SELF = "Self";

/**
 * The identity file for `declaration` in `language`, or why it cannot be
 * written: a Kotlin file needs its package, and two roles must not spell one
 * identifier.
 */
export function generateIdentity(
  declaration: IdentityDeclaration,
  language: IdentityLanguage,
  options: { readonly package?: string | undefined } = {},
): string | Unwritable {
  const { roles } = declaration;
  switch (language) {
    case "go":
      return collision(roles, pascal) ?? go(declaration);
    case "kotlin":
      if (options.package === undefined)
        return { message: "a Kotlin identity file needs --package" };
      if (!KOTLIN_PACKAGE.test(options.package))
        return {
          message: `${options.package} is not a Kotlin package name`,
        };
      return kotlin(declaration, options.package);
    case "typescript":
      return typescript(declaration);
    case "python":
      return python(declaration);
    case "rust":
      if (roles.some((role) => pascal(role) === RUST_SELF))
        return {
          message:
            "the role self is Self, a Rust keyword; rename it in the client block",
        };
      return collision(roles, pascal) ?? rust(declaration);
  }
}
